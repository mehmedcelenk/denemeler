def test_coverage():
    with open(TDE_JSON_PATH, "r", encoding="utf-8") as f:
        questions = json.load(f)

    tde1_qs = [q for q in questions if q.get("ders") == "TÜRK DİLİ VE EDEBİYATI – 1"]

    matched = 0
    total = len(tde1_qs)
    unmatched = []

    for idx, q in enumerate(tde1_qs):
        full_text = q.get("soru", "") + " " + " ".join(q.get("secenekler", {}).values())
        found = [c["term"] for c in RAW_CONCEPTS if c.get("pattern") and re.search(c["pattern"], full_text, re.IGNORECASE)]
        if found:
            matched += 1
        else:
            unmatched.append((idx + 1, q))

    print(f"=== TDE 1 KAVRAM KAPSAMA ORANI ===")
    print(f"Toplam Soru: {total}")
    print(f"Kavram Eşleşen: {matched} ({matched / total * 100:.1f}%)")
    print(f"Kavram Bulunmayan Soru: {len(unmatched)}")
    if unmatched:
        print("\nEşleşmeyen sorular:")
        for num, q in unmatched:
            print(f"[{num}] {q.get('soru')[:80]}... | {list(q.get('secenekler', {}).values())}")

    # Standardize data fields
    for item in RAW_CONCEPTS:
        item["subject"] = "TDE"
        item["ders"] = "TÜRK DİLİ VE EDEBİYATI – 1"
        item["ders_kodu"] = 541
        item["donem"] = 1

    # Save to both paths
    DATA_CONCEPTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    DOCS_CONCEPTS_PATH.parent.mkdir(parents=True, exist_ok=True)

    DATA_CONCEPTS_PATH.write_text(json.dumps(RAW_CONCEPTS, indent=2, ensure_ascii=False), encoding="utf-8")
    DOCS_CONCEPTS_PATH.write_text(json.dumps(RAW_CONCEPTS, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"\n[✓] Kavram kataloğu kaydedildi: {DATA_CONCEPTS_PATH} ({len(RAW_CONCEPTS)} kavram)")


